/*
 * inbound_readall_bounded.cpp
 *
 * **"이 프레임의 코드를 다 읽어야 한다"** 배치의 권장 설정.
 * 입고 검수, 팔레트/카트 스캔처럼 한 장에 라벨이 여럿이고 **개수를 모르는**
 * 경우다. 컨베이어 예제(conveyor_capture_controlled.cpp)와 목적이 정반대라
 * 설정도 반대 방향이다 — 저쪽은 "빨리 포기", 이쪽은 "다 찾되 상한을 건다".
 *
 * ## 이 설정이 겨냥하는 문제
 *
 * 파이프라인은 기본적으로 **코드 하나를 찾으면 끝낸다.** 개수를 알면
 * `min_expected_codes`로 알려주면 되는데, 현장에서 모르는 경우가 많다.
 * 그 격차가 그대로 검출률이다 — 같은 코퍼스가 개수를 주면 75.3%,
 * 모르면 40.0%였다(§3.92).
 *
 * ## 실측 (씨드 101 난수 코퍼스 300장, 2단계 경로, 개수 안 줌)
 *
 * 코드 단위 텍스트 일치율 / 평균 / p95. 오디코딩은 네 칸 전부 0이다.
 *
 *   auto_expected  max_frame_ms   일치율     평균     p95
 *        끔             없음       40.0%    56.1ms   322ms   <- 지금 기본
 *        끔             60ms       36.0%    15.6ms    60ms
 *        켬             없음      *73.6%*  176.9ms   440ms
 *        켬             60ms       62.9%    45.9ms   117ms
 *      **켬 + 상대마감** **60ms**  **65.6%** 58.8ms    97ms   <- 이 파일
 *
 * 마지막 줄이 이 조합의 값이다. 지금 기본과 견주면 **검출 +25.6%p,
 * 평균 +5%, p95 -70%**다. 다른 씨드(23)에서도 같은 그림이다
 * (42.4% / 58.0ms / p95 348  ->  65.8% / 58.7ms / p95 87).
 *
 * 평균을 더 줄이려면 상대 마감을 빼면 된다(넷째 줄: 62.9% / 45.9ms /
 * p95 117). 검출 2.7%p와 평균 27%를 맞바꾸는 자리다.
 *
 * ## 마감 값 고르기
 *
 * 검출은 마감 30~150ms 구간에서 **거의 평평하다**(63.6 / 63.8 / 62.9 /
 * 63.8 / 64.0%). 즉 자동 기대 개수가 벌어오는 것의 대부분은 싸다.
 * 73.6%까지 가려면 마감을 아예 풀어야 하는데, 그 마지막 10%p가 평균을
 * 4배로 만든다. 배치가 그걸 살 만한지는 배치가 정한다.
 *
 *   x86 30ms  -> 63.6%, 평균 35.0ms, p95 71.7ms
 *   x86 60ms  -> 62.9%, 평균 44.2ms, p95 107.4ms
 *   마감 없음 -> 73.6%, 평균 176.9ms, p95 440ms
 *
 * **마감은 절대 벽시계다.** 이 저장소 기준 보드(i.MX8MP)가 x86의 약 8배
 * 느리므로, 위 값을 그대로 넣으면 안 된다 — 보드에서 같은 일을 하게
 * 하려면 8배로 줄 것(x86 30ms ≒ 보드 240ms).
 *
 * ## 빌드
 *
 *   g++ -O3 -std=c++17 -Iinclude examples/inbound_readall_bounded.cpp \
 *       -Lbuild -lvscan -o inbound
 */
#include "vscan.h"

#include <cstdio>
#include <cstring>
#include <vector>

// 호출자가 채워 넣을 자리: 카메라/파일에서 프레임 한 장.
static bool grabFrame(std::vector<uint8_t>& gray, int& w, int& h);

int main() {
    vscan_config_t cfg;
    std::memset(&cfg, 0, sizeof(cfg));   // 0 초기화 = 전부 기본값

    // [1] 개수를 프레임에서 추정한다.
    //     로케이터가 준 후보 중 이미 읽은 코드로 설명되지 않는 것이 남아
    //     있으면 계속 찾는다. 코드가 하나뿐인 프레임에서는 추정값이 1이라
    //     동작도 지연도 기본과 같다 — 고정값 추측과 다른 점이 그것이다.
    cfg.auto_expected_codes = 1;

    // [2] **반드시 같이 건다.** 자동 추정은 "더 찾아라"라고만 말하고
    //     언제 멈출지는 말하지 않는다. 유령 무늬(벨트 리브, 나무결)가
    //     후보로 잡히는 프레임에서는 그 시간이 통째로 헛돈다.
    //     위 표대로 마감을 걸어도 검출은 거의 안 깎인다.
    //
    //     **보드 시간으로 줄 것**(맨 위 주석 참고). 아래 값은 x86 기준이다.
    cfg.max_frame_ms = 60;

    // [3] 상대 마감도 같이 건다. [2]는 절대 벽시계라 하드웨어가 바뀌면 뜻이
    //     바뀌는데, 이것은 "이 프레임을 한 번 훑는 값의 몇 배"라 안 바뀐다.
    //     둘을 같이 주면 이른 쪽이 마감이다.
    //     실측(씨드 101, [2]만 vs [2]+[3]): 62.9 -> 65.6%, p95 117 -> 97ms.
    //     검출을 2.7%p 벌면서 p95도 준다. 씨드 23도 같다
    //     (63.7 -> 65.8%, p95 110 -> 87ms).
    cfg.two_stage_self_budget = 1;

    // [4] 개수를 **아는** 배치라면 [1] 대신 이것을 쓸 것. 추정보다 정확하고
    //     로케이터 한 번(약 4ms)도 안 든다.
    // cfg.min_expected_codes = 6;

    // [5] 워커 구조라면 과다구독을 막는다(실측 62% 손해).
    // cfg.worker_mode = 1;

    vscan_pipeline_t* p = vscan_create(&cfg);
    if (!p) { std::fprintf(stderr, "파이프라인 생성 실패\n"); return 1; }

    std::vector<uint8_t> gray;
    int w = 0, h = 0;
    while (grabFrame(gray, w, h)) {
        vscan_result_t* r =
            vscan_process_gray_two_stage(p, gray.data(), w, h, w, /*crop_pad*/ 0);
        const size_t n = r ? r->count : 0;
        std::printf("코드 %zu개\n", n);
        for (size_t i = 0; i < n; ++i)
            std::printf("  %s\n", r->symbols[i].text);
        if (r) vscan_free_result(r);

        // [주의] 이 배치는 "다 읽었나"를 호출자가 판정해야 한다. 라이브러리는
        // 자기가 찾은 것만 돌려줄 수 있을 뿐, 프레임에 코드가 몇 개인지
        // 아는 것이 아니다(추정일 뿐이다). 개수가 정해진 공정이라면
        // n을 그 값과 대조해서 미달이면 재촬영하는 쪽이 맞다.
    }

    vscan_destroy(p);
    return 0;
}

// ---- 배치마다 다르므로 비워 둔다 ----------------------------------------
static bool grabFrame(std::vector<uint8_t>&, int&, int&) { return false; }
