#pragma once
#include "vscan_internal/frame.hpp"
#include <vector>

namespace vscan {

/*
 * [코드 후보 영역 탐지 — 심볼로지 무관]
 *
 * 왜 필요한가. 실측으로 확인된 사실인데, 실패의 원인은 "회전"이 아니라
 * **프레임 크기**였다(§3.17). 2048x1536 프레임에 128px짜리 DataMatrix를
 * 놓고 0~90도를 5도 간격으로 돌려보면 55도 이상은 전부 실패한다. 그런데
 * 같은 이미지에서 코드 주변만 205x200 ~ 665x660으로 잘라내면
 * **각도 불문 전부 읽힌다** — 회전을 한 번도 하지 않고.
 *
 *   angle=90  풀프레임 2048x1536 -> 0개
 *             여백 10 크롭 205x200 -> "VSCAN-SWEEP-01"
 *
 * 즉 zxing은 그 각도의 코드를 못 읽는 게 아니라, 큰 프레임 안에서 작은
 * 코드를 **못 찾는** 것이다. 그래서 필요한 건 더 많은 회전 시도가 아니라
 * "어디를 보라"고 알려주는 것 — 이게 산업용 리더기가 회전각과 무관하게
 * 10~20ms로 일정한 이유이기도 하다(찾기 + 작은 ROI 디코드는 각도에
 * 비례해 늘어나는 비용이 아니다).
 *
 * findDeskewCandidate()로는 안 되나. 안 된다. 그건 1D 전용이라
 * coherence(그래디언트 방향 일관성) > 0.55인 타일만 후보로 친다. 1D
 * 바코드는 막대가 전부 같은 방향이라 coherence가 높지만, QR/DataMatrix는
 * 사방으로 엣지가 뻗어 있어 coherence가 낮다 — 그래서 2D 코드에서는
 * 솔리드 L-파인더 가장자리 몇 타일만 걸리고 본체가 통째로 빠진다(실측:
 * 128x128 코드에 대해 256x128짜리 엉뚱한 bbox가 나왔다).
 *
 * 여기서는 방향을 아예 안 본다. **그래디언트 에너지만** 본다:
 * 바코드는 종류를 불문하고 주변 배경보다 단위 면적당 엣지가 압도적으로
 * 많다. 방향 조건을 빼는 것만으로 1D/2D/DPM 전부에 같은 탐지기가 쓰인다.
 */
struct CodeRegion {
    Rect bbox;      // 원본 프레임 좌표 (패딩 없음)
    float energy;   // 영역 내 그래디언트 에너지 합 — 정렬 기준

    /*
     * 영역의 지배적 기울기 추정값(도), 범위 (-45, 45].
     * rotateAroundPoint()에 -angleDeg를 넘기면 막대가 축에 정렬된다.
     *
     * 왜 findDeskewCandidate()의 추정값을 안 쓰나. 그건 후보 타일을
     * coherence > 0.55 && 에너지 상위 10%로 거른 **다음** 그 타일들만
     * 합산한다 — 1D 전용 필터라, 이미 영역을 알고 있는 상황에서는
     * 오히려 영역의 일부만 보게 된다. 실측: PDF417 크롭에서 20/30/60/75/80도
     * 전부 "추정 불가"(coherence < 0.25)가 나왔는데, 정작 그 각도들은
     * 전부 정확한 각도 한 번의 회전으로 읽혔다(각각 +20 / +30 / -30 /
     * -15 / -10도). 즉 정보가 없던 게 아니라 필터가 버린 것이다.
     * 여기서는 그 영역에 속한 hot 타일 전체의 텐서를 합산한다.
     *
     * 2D 행렬코드(QR/DataMatrix)는 사방으로 엣지가 뻗어 방향성이 없어
     * kAngleUnknown이 나오는 게 정상이다 — 그런 코드는 애초에 회전이
     * 필요 없다(ROI로 자르기만 하면 전 각도가 읽힌다).
     */
    static constexpr float kAngleUnknown = 1e9f;
    float angleDeg = kAngleUnknown;
};

/*
 * 에너지가 큰 순으로 최대 maxRegions개의 후보 영역을 돌려준다.
 *
 * tileSize/downscale은 findDeskewCandidate()와 같은 뜻이다(기본
 * 32 x 4배 = 원본 128px 타일). 이 크기는 "코드 하나가 타일 몇 개에
 * 걸치느냐"만 좌우하고, 인접 타일을 연결해서 덩어리를 만들기 때문에
 * 코드가 타일보다 크든 작든 상관없다.
 *
 * energyRatio: 프레임 내 최대 타일 에너지 대비 몇 배 이상이면 후보로
 * 볼지. 절대 임계값을 안 쓰는 이유는 노출/대비가 프레임마다 다르기
 * 때문 — 상대값이라 자동으로 적응한다.
 */
std::vector<CodeRegion> findCodeRegions(const GrayView& image, int maxRegions = 4,
                                        int tileSize = 32, int downscale = 4,
                                        float energyRatio = 0.20f);
/*
 * [각도 정밀화] 영역 안에서 **원본 해상도로** 구조텐서를 다시 재서
 * 기울기를 돌려준다. 방향성이 약하면 CodeRegion::kAngleUnknown.
 *
 * 왜 필요한가. findCodeRegions()의 angleDeg는 4배 축소본에서 나온 값인데,
 * 축소가 각도를 **축(0도) 쪽으로 끌어당긴다**. 박스 다운샘플이 고주파를
 * 깎는 방식이 x/y 축에 정렬돼 있어서 생기는 앨리어싱이다. 실측(PDF417,
 * 각도를 (-45,45]로 접은 참값 대비):
 *
 *   참값    -5    -10    -20    -25    -30    -35    30(60도)   15(75도)
 *   4배   -4.6   -8.5  -17.2  -21.9  -26.9  -33.2      25.8       11.2
 *   2배   -4.7   -9.4  -18.9  -23.9  -28.5  -34.4      28.3       13.6
 *   1배   -4.9   -9.8  -19.6  -24.6  -29.1  -34.9      28.9       14.3
 *
 * 4배에서 오차가 최대 4.2도인데 원본에서는 0.7도다. PDF417은 되돌린 뒤
 * 읽히는 각도 창이 8도 남짓이라, 3~4도 오차면 창을 벗어난다 — 실제로
 * 25/30도가 정확히 그렇게 실패했다.
 *
 * 비용은 영역 크기에 비례한다. 영역은 보통 프레임의 1~20%이고, 회전을
 * 시도하는 프레임(다른 게 전부 실패한 프레임)에서만 부른다.
 */
float refineRegionAngle(const GrayView& image, const Rect& bbox);

/*
 * [상자 정밀화] 영역 상자를 **원본 해상도로** 다시 재서 좁힌다.
 *
 * 왜 필요한가. findCodeRegions()의 상자는 타일 격자(기본 원본 128px)
 * 단위라 코드보다 늘 헐렁하다. 거기에 호출부가 정지대용 여백까지 붙이면
 * "ROI"가 ROI가 아니게 된다 — 실측(Code128 module 8, 대비 0.10,
 * 2048x1536): 영역 크롭이 1184x832 = 985k px로 **프레임의 31%**인데
 * 정작 코드는 1023x399(13%)다.
 *
 * 그 차이가 그대로 시간이다. 같은 프레임에서 zxing 호출을 찍어보면
 * 985k px 풀옵션 디코드가 13.6~27.2ms인데 408k px는 13.1ms다. 게다가
 * 저대비/회전/노이즈 경로가 전부 같은 rect를 쓰므로 한 번 좁히면
 * 모든 구제 단계에 그대로 곱해진다.
 *
 * 각도를 원본 해상도로 다시 재서 오차를 4.2도 -> 0.7도로 줄인 것과
 * 같은 수법이다(refineRegionAngle 위 주석). 축소본은 어디에 있는지
 * 알려주는 데까지만 쓰고, 정확한 값은 원본에서 다시 잰다.
 *
 * 방법은 행/열별 그래디언트 에너지 프로파일이다. 바코드는 종류를 불문하고
 * 배경보다 단위 길이당 엣지가 압도적으로 많으므로, 프로파일이 낮아지는
 * 지점이 코드의 경계다. 두 가지가 결정적이다(둘 다 실패해보고 알았다):
 *
 *  - **임계를 최대값이 아니라 백분위수로 잡는다.** 라벨 종이 가장자리는
 *    한 행에 수백 픽셀짜리 단차가 통째로 들어가 최대값을 혼자 정한다.
 *    그 기준으로는 코드 행 0.19 / 배경 행 0.15로 붙어버려서 0.12~0.55
 *    어떤 값으로도 안 갈렸다. p10을 바닥, p90을 꼭대기로 삼으면 갈린다.
 *  - **열은 1차에서 찾은 행 범위 안에서만 잰다.** 창 전체에서 재면
 *    코드가 없는 행들이 모든 열에 똑같이 더해져 차이가 희석된다.
 *    실제로 행은 제대로 잡히는데 열만 창 전체로 나왔다.
 *
 * 결과가 원래 상자보다 넓으면 판정 실패로 보고 원래 상자를 쓴다.
 * energyRatio 0.30은 실측에서 왔다 — 0.5/0.7로 올리면 45도 회전 코드가
 * 678x678에서 331x522로 잘린다(대각선 방향으로 에너지가 옅어지기 때문).
 *
 * searchMargin: 프로파일을 재기 전에 상자를 이만큼 넓혀서 본다. 타일
 * 격자가 코드의 가장자리를 잘라먹었을 수 있으므로(에너지가 약한 정지대
 * 쪽 타일이 임계를 못 넘는 경우), 한 타일만큼 넓혀놓고 다시 찾는다.
 * 넓힌 창 안에서 다시 좁히는 것이라 결과가 원래 상자보다 커질 수도 있고,
 * 그건 잘려 있었다는 뜻이라 맞는 동작이다.
 */
Rect refineRegionBox(const GrayView& image, const Rect& bbox,
                     float energyRatio = 0.30f, int searchMargin = 64);

} // namespace vscan
