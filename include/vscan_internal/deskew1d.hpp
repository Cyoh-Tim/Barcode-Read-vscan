#pragma once
#include "vscan_internal/frame.hpp"

namespace vscan {

// [1D 바코드 회전 구제 — 위치 탐지] 정상 폴백 체인(§3.2.12~13)이 전부
// 실패했을 때 마지막으로 시도하는 5단계용. 실물 산업용 리더기 실측으로
// 확인된 20~75도 부근 회전 1D 바코드는 zxing이 풀옵션으로도 못 찾는데
// (§3.2.15/16), 이건 위치를 몰라서가 아니라 "그 위치에서도 각도가
// 안 맞아서" 실패하는 것이다. 그래서 정밀한 각도 추정 대신, "1D 바코드
// 처럼 보이는 영역이 대략 어디인지"만 싸게 찾고, 각도는 zxing에게
// 직접 몇 번 물어보는 방식(§ 대화 실측: 위치를 안다는 전제 하에
// 45도 사전회전 단 1회로 24~66도 갭이 완전히 메워짐)을 쓴다.
//
// 알고리즘: 프레임을 큼직한 타일(기본 128px 원본 기준)로 나눠, 타일별로
// Sobel 그래디언트의 구조텐서 일관성(coherence)을 본다. 1D 바코드는
// 국소적으로 그래디언트 방향이 한쪽으로 몰려있어(막대가 전부 같은
// 방향) coherence가 높다 — 텍스트/일반 배경보다 뚜렷이 구분된다.
// 타일 단위 블록 리덕션이라 이진화 NEON 패치(§6.5.1)와 같은 패턴으로
// 자동 벡터화된다.
//
// 이 탐지기는 "정확한 각도"가 아니라 "대략적인 위치"만 필요하다 —
// 그래서 정밀도 요구가 낮고, 큰 타일 단위로도 충분하다. 정밀한 각도는
// 회전 구제 단계(pipeline.cpp)에서 zxing 디코드 성공 여부로 직접
// 검증하므로, 여기서 오차가 있어도 최종 결과의 정확성에는 영향이 없다
// (최종 안전망은 언제나 zxing의 체크섬 검증).
struct DeskewCandidate {
    Rect bbox;       // 원본 프레임 좌표계의 후보 영역 (패딩 없음)
    float coherence;  // 참고용 — 디버깅/튜닝에만 사용, 판정에는 안 씀
};

// 가장 강한(면적이 가장 큰) 후보 하나를 찾는다. 없으면 false.
bool findDeskewCandidate(const GrayView& image, DeskewCandidate& out,
                          int tileSize = 32, int downscale = 4,
                          float minCoherence = 0.55f);

} // namespace vscan
