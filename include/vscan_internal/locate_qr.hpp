#pragma once
#include "vscan_internal/frame.hpp"
#include <vector>

namespace vscan {

/*
 * [QR 파인더 패턴 탐지 — 작고 흐린 QR 전용]
 *
 * 왜 별도 탐지기인가. findCodeRegions()(locate.hpp)는 그래디언트 에너지만
 * 보므로 심볼로지를 안 가리는 대신, **작은 코드가 여러 개 흩뿌려진 프레임**
 * 에서는 원리적으로 못 쓴다:
 *   - 타일이 원본 128px이라 45px짜리 코드 여러 개가 한 타일에 뭉친다.
 *   - 에너지 순위가 면적에 좌우돼서, 큰 글자 블록이 작은 QR을 밀어낸다.
 *     실측(실물 3.1MP 해상도 차트): 상위 2개가 "AUTONICS 3.1MP"(896x128)와
 *     좌상단 텍스트 덩어리(640x896)였다.
 *
 * 여기서는 QR **고유의 구조**를 쓴다. 파인더 패턴(세 모서리의 겹눈 사각형)은
 * 어느 방향으로 잘라도 흑:백:흑:백:흑 = 1:1:3:1:1 비율로 나온다. 이 비율은
 * 크기와 회전에 불변이라, 코드가 작아도 흐려도 비율만 살아있으면 걸린다.
 *
 * 실측(같은 차트, 모듈 2.1px): 파인더 후보 64개 -> 직각이등변 3개 조합으로
 * QR 후보 11곳. 변 길이에서 역산한 모듈이 2.16~2.51px로 실제(2.1px)와
 * 맞고, **11곳 중 9곳이 "잘라주면 읽히는" 지점**이었다. 즉 읽을 수 있는
 * 코드를 정확히 집어낸다.
 *
 * 비용이 있으므로(전체 행 스캔) 다른 모든 단계가 실패한 뒤에만 부른다.
 */
struct QrCandidate {
    Rect bbox;        // 코드 전체를 감싸는 상자 (정지대 제외)
    float modulePx;   // 파인더에서 잰 모듈 한 칸의 픽셀 크기
};

/*
 * 파인더 패턴 세 개가 직각이등변을 이루는 조합을 찾아 QR 후보를 돌려준다.
 *
 * minModulePx: 이보다 작은 모듈은 후보에서 뺀다. 기본 0.8px — 그 아래는
 *   1:1:3:1:1을 이룰 픽셀 자체가 없어서 잡히는 게 전부 잡음이다.
 * maxModulePx: 이보다 큰 모듈은 후보에서 뺀다. 기본 6.0px.
 *   이 탐지기는 "모듈이 작아서 일반 경로가 놓친 코드"를 위한 것이다.
 *   모듈이 4px를 넘는데 못 읽혔다면 원인이 크기가 아니므로 여기서
 *   찾아봐야 얻을 게 없고, 대신 난수 코퍼스처럼 정상 크기 코드가 있는
 *   프레임에서 헛후보가 나와 ROI 확대 디코드를 헛돌린다 —
 *   실측으로 코퍼스 평균이 24% 늘었다.
 * rowStep: 몇 행마다 스캔할지. **1이 기본이고, 2로 올리면 안 된다.**
 *   "파인더가 세로 7모듈이니 2행 간격이어도 여러 번 걸린다"고 보고 2로
 *   뒀다가 실측에서 후보가 11곳 -> 4곳으로 반토막 났다(파인더점 68 -> 33).
 *   흐린 이미지에서는 각 행의 1:1:3:1:1이 아슬아슬하게 통과/탈락하므로,
 *   행을 건너뛰면 통과하는 행 자체를 놓친다. 비용 차이는 8.1 vs 5.4ms다.
 */
std::vector<QrCandidate> findQrCandidates(const GrayView& image, int maxCandidates = 16,
                                          float minModulePx = 0.8f, float maxModulePx = 6.0f,
                                          int rowStep = 1);

} // namespace vscan
