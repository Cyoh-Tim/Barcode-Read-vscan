namespace vscan {

/*
 * [곡면(원통 라벨) 보정 — 국소 바 피치를 균등하게]
 *
 * 원통에 감긴 라벨은 위치에 따라 가로 배율이 달라진다. 원근(§3.31)과
 * 다른 점은 **상자가 직사각형 그대로**라는 것이다 — 가로 좌표만 비선형으로
 * 밀리고 세로는 그대로다. 그래서 호모그래피로는 원리적으로 못 편다
 * (perspectiveRectify()는 "이미 직사각형"이라며 손을 뗀다).
 *
 * 실측(module 8, 곡면 축 — 강도 1.0이 왜곡 없음, 낮을수록 강함):
 *   DataBar 0.8 미만 전부 실패 / DataBarExp 0.7 미만 / UPCE 0.5 미만 /
 *   PDF417 0.4 미만
 * 그러면서 코드는 멀쩡하다 — 중앙행 런이 45개로 왜곡 강도와 무관하게
 * 유지되고 최소 바 폭도 6~9px다. 즉 정보는 있고 리더가 못 읽는 것이다.
 *
 * 방법은 모델 없이 간다. "한 모듈이 몇 픽셀인가"를 x의 함수 m(x)로
 * 추정하고, du/dx = 1/m(x)로 정의되는 좌표 u(모듈 단위)에서 균등하게
 * 다시 샘플링한다. 생성기가 쓰는 특정 원통 모델을 가정하지 않으므로
 * 하네스에 과적합되지 않는다.
 *
 * m(x)는 런 길이를 x 위치로 묶어서 낸다. 런 길이는 모듈의 정수배(1~4배)
 * 이므로 창 안의 **하위 백분위수**가 곧 1모듈이다. 이 두 값(창 크기와
 * 백분위수)은 민감하다 — 30퍼센타일까지 올리면 하나도 안 열린다. 런 길이
 * 분포가 코드마다 다르고, 백분위수가 높으면 2모듈짜리 런을 1모듈로
 * 착각하기 때문이다. 그래서 하나로 못 정했다(아래).
 *
 * [모수를 하나로 정할 수 없었다 — 파이프라인이 세 벌을 부른다]
 * rows==1은 전환이 가장 많은 한 행만 본다. rows>1은 코드 높이를 균등
 * 분할한 행들의 런을 한 통에 붓는다. 적층 코드(PDF417 / DataBar Expanded)는
 * 행마다 내용이 달라 한 행이 그 열의 모듈을 대표하지 못하니 여러 행이
 * 유리할 것 같지만, **실측은 트레이드오프였다**(곡면 축 11단계, module 8):
 *
 *              rows=1   rows=9   합집합
 *   DataBar     9/11     8/11    10/11   <- 9행이 0.4를 살리고 0.6/0.7을 죽였다
 *   DataBarExp  7/11     9/11    10/11
 *   PDF417      8/11     8/11     8/11
 *
 * 창 크기와 백분위수도 마찬가지였다. (rows, winRuns, pct) 격자를 돌려보니
 * 세 벌이 각각 자기만 여는 구간을 갖는다:
 *   (1,13,10)  DataBar 0.6/0.7
 *   (9,21,5)   PDF417 0.2/0.3, DataBar 0.1, DataBarExp 0.1
 *   (9,13,10)  DataBarExp 0.2
 * 셋을 다 돌리면 DataBar/DataBarExp 곡면이 11/11, PDF417이 10/11이다.
 * 그래서 파이프라인은 구제 사다리에서 이 순서로 **셋 다** 부른다.
 * 사다리 맨 끝이라 이미 다 실패한 프레임에서만 뒤 벌이 돈다
 * (값은 치른다 — pipeline.cpp의 해당 자리 주석).
 *
 * 창을 잡는 법도 갈린다. 1행은 런 인덱스로 세는 창(앞뒤 winRuns개)이고,
 * 여러 행은 런이 x축에서 뒤섞여 인덱스가 물리적 폭을 뜻하지 않으므로
 * 픽셀 창(중간 런 길이 x winRuns)이다. 처음에 9행용 픽셀 창을 1행에도
 * 그대로 썼더니 rows=1이 예전과 달라져 DataBar 0.6/0.7이 죽었다.
 * **두 추정기는 결과가 다르다 — 섞지 말 것.**
 *
 * [한계] PDF417 곡면 0.1은 위 격자 어느 칸으로도 안 열렸다.
 * [[vscan-lite-pitch-equalize]]
 */
struct PitchMap {
    std::vector<float> srcX;   // 출력 x(여백 제외) -> 원본 x
    int marginX = 0, marginY = 0;
};

bool pitchEqualize(const GrayView& src, GrayImage& out, PitchMap* map = nullptr,
                   int rows = 1, int winRuns = 13, int pct = 10, float outModule = 8.0f);

} // namespace vscan
